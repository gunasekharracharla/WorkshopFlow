"""Regenerate frontend/countries.js (country list + per-country phone rules).

Requires:  pip install phonenumbers babel
Run from the project root:  python scripts/generate_countries.py

Each entry: [ISO2, display name, calling code, national-number regex, example number]
The regex is built from libphonenumber metadata (fixed line | mobile | VoIP), i.e. the
same data the backend's `phonenumbers` validation uses. India is intentionally handled
in app.js with the simple, well-known rule [6-9]\\d{9}.
"""
import json
import pathlib
import unicodedata

import phonenumbers
from babel import Locale
from phonenumbers import PhoneMetadata, PhoneNumberType

NAME_OVERRIDES = {
    "HK": "Hong Kong",
    "MO": "Macau",
    "MM": "Myanmar",
    "TR": "Türkiye",
    "CD": "DR Congo",
    "CG": "Congo (Republic)",
    "CI": "Côte d'Ivoire",
    "FK": "Falkland Islands",
    "PS": "Palestine",
    "VA": "Vatican City",
    "TL": "Timor-Leste",
    "SZ": "Eswatini",
    "CV": "Cape Verde",
    "BQ": "Caribbean Netherlands",
    "AC": "Ascension Island",
    "TA": "Tristan da Cunha",
}


def strip_accents(text: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFD", text) if unicodedata.category(c) != "Mn")


def build():
    territories = Locale("en").territories
    rows = []
    for region in phonenumbers.SUPPORTED_REGIONS:
        meta = PhoneMetadata.metadata_for_region(region)
        patterns = []
        for desc in (meta.fixed_line, meta.mobile, meta.voip):
            pattern = desc.national_number_pattern if desc else None
            if pattern and pattern != "NA" and pattern not in patterns:
                patterns.append(pattern)
        pattern = "|".join(patterns) if len(patterns) > 1 else (patterns[0] if patterns else "")
        example = ""
        for kind in (PhoneNumberType.MOBILE, PhoneNumberType.FIXED_LINE):
            sample = phonenumbers.example_number_for_type(region, kind)
            if sample:
                example = phonenumbers.national_significant_number(sample)
                break
        if region == "IN":
            pattern = r"[6-9]\d{9}"  # India: mobile numbers only, as accepted by the original form
        name = NAME_OVERRIDES.get(region) or territories.get(region) or region
        rows.append([region, name, str(phonenumbers.country_code_for_region(region)), pattern, example])
    rows.sort(key=lambda r: strip_accents(r[1]).lower())
    india = next(r for r in rows if r[0] == "IN")
    rows.remove(india)
    rows.insert(0, india)  # India is the default / first entry
    return rows


if __name__ == "__main__":
    rows = build()
    out = pathlib.Path(__file__).resolve().parent.parent / "frontend" / "countries.js"
    body = ",\n".join(json.dumps(r, ensure_ascii=False, separators=(",", ":")) for r in rows)
    out.write_text(
        "/* Generated by scripts/generate_countries.py - do not edit by hand.\n"
        "   [ISO2, name, calling code, national-number regex, example number] */\n"
        "window.WORKSHOP_COUNTRIES = [\n" + body + "\n];\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(rows)} countries to {out} ({out.stat().st_size} bytes)")
